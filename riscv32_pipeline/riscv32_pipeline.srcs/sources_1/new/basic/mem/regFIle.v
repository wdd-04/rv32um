`include "../../param.v"

/**
 * @Module: RegFile
 * @Description: 通用寄存器堆。
 *               实现 RISC-V 的 32 个 32 位寄存器。
 *               特点：
 *               1. x0 恒为 0。
 *               2. 内部前推：若读写地址相同，直接输出待写入数据，解决单周期内的读写冲突。
 *               3. 下沿写入：采用时钟下降沿更新数据，增加写回阶段到译码阶段的数据建立时间。
 */
module RegFile(
           input   wire          clk,
           input   wire          rst_n,
           input   wire          we,        // 写使能信号
           input   wire[4: 0]    rs1,       // 源寄存器 1 地址
           input   wire[4: 0]    rs2,       // 源寄存器 2 地址
           input   wire[4: 0]    wr,        // 目标寄存器写地址
           input   wire[31: 0]   wd,        // 目标寄存器写数据
           output  wire[31: 0]   rd1,       // 源寄存器 1 读出数据
           output  wire[31: 0]   rd2        // 源寄存器 2 读出数据
       );

// 寄存器阵列定义：由于 x0 恒为 0，实际存储空间为 31 到 1
reg[31: 0] rf[31: 1]; 

// =================================================================
// 寄存器读取逻辑 (Register Read with Internal Forwarding)
// =================================================================

// 内部前推检测：判断当前周期是否正在写入同一个寄存器，且该寄存器不是 x0
wire write_hit_rs1 = (we == `REGWE_WRITE) && (wr != 5'd0) && (wr == rs1);
wire write_hit_rs2 = (we == `REGWE_WRITE) && (wr != 5'd0) && (wr == rs2);

// 读端口 1 逻辑
assign rd1 = (rs1 == 0) ? 32'b0 : // x0 恒为 0
             (write_hit_rs1 ? wd : rf[$unsigned(rs1)]); // 如果写碰读，前推数据；否则读寄存器

// 读端口 2 逻辑
assign rd2 = (rs2 == 0) ? 32'b0 : // x0 恒为 0
             (write_hit_rs2 ? wd : rf[$unsigned(rs2)]); // 如果写碰读，前推数据；否则读寄存器

// =================================================================
// 寄存器写入逻辑 (Register Write - Negative Edge)
// =================================================================

// 采用时钟下降沿写入，通常用于简化流水线中的数据相关处理
always @ (negedge clk or negedge rst_n) begin
    if (~rst_n) begin
        // 同步复位：将所有寄存器清零
        rf[1][31: 0]  <= 0;
        rf[2][31: 0]  <= 0;
        rf[3][31: 0]  <= 0;
        rf[4][31: 0]  <= 0;
        rf[5][31: 0]  <= 0;
        rf[6][31: 0]  <= 0;
        rf[7][31: 0]  <= 0;
        rf[8][31: 0]  <= 0;
        rf[9][31: 0]  <= 0;
        rf[10][31: 0] <= 0;
        rf[11][31: 0] <= 0;
        rf[12][31: 0] <= 0;
        rf[13][31: 0] <= 0;
        rf[14][31: 0] <= 0;
        rf[15][31: 0] <= 0;
        rf[16][31: 0] <= 0;
        rf[17][31: 0] <= 0;
        rf[18][31: 0] <= 0;
        rf[19][31: 0] <= 0;
        rf[20][31: 0] <= 0;
        rf[21][31: 0] <= 0;
        rf[22][31: 0] <= 0;
        rf[23][31: 0] <= 0;
        rf[24][31: 0] <= 0;
        rf[25][31: 0] <= 0;
        rf[26][31: 0] <= 0;
        rf[27][31: 0] <= 0;
        rf[28][31: 0] <= 0;
        rf[29][31: 0] <= 0;
        rf[30][31: 0] <= 0;
        rf[31][31: 0] <= 0;
    end
    else if (we == `REGWE_WRITE && wr != 5'd0) begin
        // 执行写入操作，禁止写入 x0
        rf[$unsigned(wr)] <= wd;
    end
end

endmodule