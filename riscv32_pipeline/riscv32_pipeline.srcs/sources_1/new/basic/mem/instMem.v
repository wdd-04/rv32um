/**
 * @Module: InstMem
 * @Description: 指令存储器适配层。
 *               作为处理器的指令 ROM 接口，负责将 PC 地址转换为存储器 IP 核所需的地址格式。
 */
module InstMem(
           input   wire        clk,
           input   wire        rst_n,
           input   wire        flush,
           input   wire[31: 0] pc,   // 来自取指阶段的 32 位程序计数器
           output  wire[31: 0] inst  // 输出对应的 32 位机器码
       );

// =================================================================
// 未使用信号处理
// =================================================================
// 部分 FPGA 厂商的 ROM IP 不支持异步复位或清空，此处保留接口以维持顶层兼容性
wire unused_rst_n = rst_n;
wire unused_flush = flush;

// =================================================================
// 实例：底层存储器 IP 核 (inst_mem)
// =================================================================
inst_mem irom(
             .clka(clk),
             
             // 地址转换逻辑：
             // 由于 RISC-V 指令是 4 字节对齐的 (32-bit)，底层存储器通常以字(Word)为单位寻址。
             // 因此需要去掉 PC 的低 2 位 (pc[1:0])，将字节地址转换为字地址。
             // 此处选取 pc[15:2] 是因为存储器深度通常设为 16384 (2^14) 或根据具体 SoC 空间定义。
             .addra(pc[15: 2]), 
             
             .douta(inst)      // 输出指令
         );

endmodule